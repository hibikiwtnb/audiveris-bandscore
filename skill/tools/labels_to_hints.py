#!/usr/bin/env python3
"""Draft context/instrument_changes.txt from the printed timbre / octave labels.

    python3 tools/labels_to_hints.py "<song dir>" [--part "Key."] > /tmp/hints.txt

Runs tools/locate_labels.py, keeps the instrument labels (including labels such as
"Glocken(8va)" and "Pan Flute (8va)"), and writes a staff-aware hint file that
tools/apply_instrument_changes.py can apply. The result is a DRAFT: unnamed or unknown
timbres are reported as ``# check:`` comments, and the printed label position is
measure-granular (a change printed mid-measure is moved to that measure's start).
Review the draft against the score before using it; this tool never writes into the
song directory.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from apply_instrument_changes import DEFAULT_TIMBRES  # noqa: E402

LABEL_RE = (r"8va|15ma|coll|pizz|arco|bell|glock|harp|woodwind|flute|oboe|clarinet|bassoon|"
            r"horn|trumpet|trombone|brass|strings|piano|organ|pluck|celesta|marimba|vibes|"
            r"synth|pad|lead|seq|arpegg|choir|voice|whistle|cymbal|steel|scratch|sweep")
OCTAVE_RE = re.compile(r"(15\s*ma|8\s*va)", re.I)
COLL_RE = re.compile(r"coll", re.I)
CLEAN = re.compile(r"^[\s\-—–~∼¬→←┌┐↓|()（）\[\]<>'\"·.,:;]+|"
                   r"[\s\-—–~∼¬→←┌┐↓|()（）\[\]<>'\"·.,:;]+$")
SPACE = re.compile(r"\s+")
DIRS = {k.upper().replace('.', '').replace(' ', ''): k for k in DEFAULT_TIMBRES}


def known_timbre(text):
    """Return (timbre, octave, coll) for one printed label, or (None, why, False)."""
    octave = 0
    coll = bool(COLL_RE.search(text))
    if OCTAVE_RE.search(text) and not coll:
        octave = 2 if re.search(r"15\s*ma", text, re.I) else 1
    body = OCTAVE_RE.sub(' ', text)
    body = COLL_RE.sub(' ', body)
    body = CLEAN.sub('', body)
    body = body.replace('(', ' ').replace(')', ' ')
    body = SPACE.sub(' ', body).strip()
    # longest known name inside the label wins ("Synth. Strings" before "Strings")
    hits = sorted((name for name in DEFAULT_TIMBRES
                   if name.upper().replace('.', '') in body.upper().replace('.', '')
                   or name.upper().replace('.', '').replace(' ', '')
                   in body.upper().replace('.', '').replace(' ', '')),
                  key=len, reverse=True)
    if hits:
        return hits[0], octave, coll
    return None, body, coll


def rows(song_dir, part):
    cmd = [sys.executable, os.path.join(HERE, 'locate_labels.py'), song_dir, LABEL_RE]
    out = subprocess.run(cmd, capture_output=True, text=True, check=True,
                         env=dict(os.environ, PYTHONIOENCODING='utf-8')).stdout
    for line in out.splitlines()[1:]:
        f = line.split('\t')
        if len(f) < 8 or (part and f[2] != part):
            continue
        if float(f[6]) < 250:       # left-margin staff name, not a timbre label
            continue
        yield dict(page=f[0], system=f[1], part=f[2], staff=f[3], measure=f[4],
                   beat=f[5], x=float(f[6]), text=f[7])


def num(measure):
    return int(measure) if measure.isdigit() else 10**9


def main(song_dir, part):
    defaults, changes, warnings = {}, [], []
    for r in rows(song_dir, part):
        name, octave, coll = known_timbre(r['text'])
        if name is None:
            warnings.append(f"m{r['measure']} {r['part']} staff {r['staff']} "
                            f"{r['text']!r}: no known timbre ({octave})")
            continue
        if coll:
            warnings.append(f"m{r['measure']} {r['part']} staff {r['staff']} "
                            f"{r['text']!r}: coll'8va is not applied by instrument changes")
        key = (r['part'], r['staff'])
        if r['text'].lstrip().startswith('-') and key in defaults:
            warnings.append(f"m{r['measure']} {r['part']} staff {r['staff']} "
                            f"{r['text']!r}: printed end mark, add the return timbre by hand")
        if key not in defaults:
            defaults[key] = name
            continue
        changes.append(dict(measure=r['measure'], part=r['part'], staff=r['staff'],
                            label=r['text'], timbre=name, octave=octave,
                            beat=float(r['beat']) if r['beat'] not in ('end', '?') else 99))
    print('# DRAFT generated by tools/labels_to_hints.py; review against the score.')
    if warnings:
        for w in warnings:
            print(f'# check: {w}')
    print('[defaults]')
    for (p, s), name in sorted(defaults.items()):
        print(f'{p}\t{name}\t{s}')
    print('[changes]')
    state = dict(defaults)
    for c in sorted(changes, key=lambda c: (c['part'], c['staff'], num(c['measure']),
                                            c['beat'])):
        key = (c['part'], c['staff'])
        if c['timbre'] == state[key] and c['octave'] == 0:
            continue
        state[key] = c['timbre']
        print(f"{c['measure']}\t{c['part']}\t{c['staff']}\t{c['label']}\t{c['timbre']}"
              f"\t{c['octave']}")


if __name__ == '__main__':
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    part = next((a.split('=', 1)[1] for a in sys.argv[1:] if a.startswith('--part=')), '')
    if not args:
        sys.exit('Usage: tools/labels_to_hints.py "<song dir>" [--part=ABBR]')
    main(args[0], part)
